-- Aplicar en un proyecto Supabase nuevo. No ejecutar el modelo histórico de EVA2.
begin;
create table public.app_profiles (
  id uuid primary key references auth.users(id),
  role text not null check (role in ('Administrador','Mentor','Mentoreado')),
  active boolean not null default true
);
create table public.mentors (
  id uuid primary key, user_id uuid unique references public.app_profiles(id),
  name text not null check (length(trim(name)) between 1 and 100),
  title text not null default '' check (length(title)<=150),
  email text not null default '' check (email='' or email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  phone text not null default '' check(length(phone)<=30),
  expertise text[] not null default '{}' check(cardinality(expertise)<=20),
  bio text not null default '' check(length(bio)<=2000), photo text,
  version integer not null default 0
);
create table public.mentees (
  id uuid primary key, user_id uuid unique references public.app_profiles(id),
  name text not null check (length(trim(name)) between 1 and 100),
  venture text not null default '' check(length(venture)<=150),
  stage text not null default '' check(length(stage)<=100),
  email text not null default '' check (email='' or email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  phone text not null default '' check(length(phone)<=30),
  need text not null default '' check(length(need)<=2000), photo text,
  version integer not null default 0
);
create table public.mentorships (
  id uuid primary key,
  "sourceNumber" bigint generated by default as identity unique,
  "mentorId" uuid not null references public.mentors(id),
  "menteeId" uuid not null references public.mentees(id),
  year integer not null default extract(year from current_date) check(year between 2000 and 2100),
  month text not null default '' check(month in ('','Enero','Febrero','Marzo','Abril','Mayo','Junio','Julio','Agosto','Septiembre','Octubre','Noviembre','Diciembre')),
  hours numeric not null default 0 check(hours>=0 and hours<=10000),
  space text not null default '' check(length(space)<=200),
  status text not null default 'En proceso' check(status in ('Suspendida','En proceso','Terminada','No corresponde','Esperando derivación','Derivada')),
  service text not null default '' check(service in ('','Mentoría administrativa y financiera','Mentoría en gestión comercial','Mentoría en informática y ciberseguridad')),
  formalization text not null default 'Pendiente' check(formalization in ('Pendiente','Sí','No','No corresponde')),
  "planningSir" text not null default 'Pendiente' check("planningSir" in ('Pendiente','Sí','No','No corresponde')),
  "executionSir" text not null default 'Pendiente' check("executionSir" in ('Pendiente','Sí','No','No corresponde')),
  "paidAt" date, goal text not null default '' check(length(goal)<=2000),
  version integer not null default 0
);
create table public.sessions (
  id uuid primary key default gen_random_uuid(),
  "mentorshipId" uuid not null references public.mentorships(id),
  number smallint not null check(number between 1 and 6), date date,
  status text not null default 'Pendiente' check(status in ('Pendiente','Agendada','Realizada','Reprogramada')),
  summary text not null default '' check(length(summary)<=2000),
  version integer not null default 0,
  unique("mentorshipId",number),
  check(status='Pendiente' or date is not null),
  check(status<>'Realizada' or length(trim(summary))>0)
);
create table public.evidence (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references public.sessions(id),
  kind text not null check(kind in ('photo','document')),
  path text unique not null, name text not null check(length(name) between 1 and 255),
  type text not null, size integer not null check(size>0),
  unique(session_id,kind),
  check((kind='photo' and type in ('image/png','image/jpeg') and size<=2097152)
     or (kind='document' and type='application/pdf' and size<=5242880))
);
create table public.audit_events (
  id bigint generated always as identity primary key,
  actor uuid not null references public.app_profiles(id), entity text not null,
  record_id uuid not null, operation text not null, occurred_at timestamptz not null default now()
);
create table public.write_limits (actor uuid primary key references public.app_profiles(id), since timestamptz not null, count integer not null);
create index on public.mentorships("mentorId");
create index on public.mentorships("menteeId");

create function public.app_role() returns text language sql stable security definer set search_path='' as $$
 select role from public.app_profiles where id=auth.uid() and active
$$;
create function public.can_view_mentorship(mid uuid) returns boolean language sql stable security definer set search_path='' as $$
 select coalesce(public.app_role()='Administrador' or exists(
   select 1 from public.mentorships m
   left join public.mentors r on r.id=m."mentorId" left join public.mentees e on e.id=m."menteeId"
   where m.id=mid and ((public.app_role()='Mentor' and r.user_id=auth.uid())
     or (public.app_role()='Mentoreado' and e.user_id=auth.uid()))),false)
$$;
create function public.can_edit_mentorship(mid uuid) returns boolean language sql stable security definer set search_path='' as $$
 select coalesce(public.app_role()='Administrador' or (public.app_role()='Mentor' and exists(
   select 1 from public.mentorships m join public.mentors r on r.id=m."mentorId" where m.id=mid and r.user_id=auth.uid())),false)
$$;
alter table public.app_profiles enable row level security;
alter table public.mentors enable row level security;
alter table public.mentees enable row level security;
alter table public.mentorships enable row level security;
alter table public.sessions enable row level security;
alter table public.evidence enable row level security;
alter table public.audit_events enable row level security;
alter table public.write_limits enable row level security;
create policy profile_read on public.app_profiles for select to authenticated using(id=auth.uid() and active);
create policy mentors_read on public.mentors for select to authenticated using(public.app_role()='Administrador' or (public.app_role() is not null and (user_id=auth.uid() or exists(select 1 from public.mentorships m where m."mentorId"=mentors.id and public.can_view_mentorship(m.id)))));
create policy mentees_read on public.mentees for select to authenticated using(public.app_role()='Administrador' or (public.app_role() is not null and (user_id=auth.uid() or exists(select 1 from public.mentorships m where m."menteeId"=mentees.id and public.can_view_mentorship(m.id)))));
create policy mentorship_read on public.mentorships for select to authenticated using(public.can_view_mentorship(id));
create policy session_read on public.sessions for select to authenticated using(public.can_view_mentorship("mentorshipId"));
create policy evidence_read on public.evidence for select to authenticated using(exists(select 1 from public.sessions s where s.id=session_id));
create policy audit_read on public.audit_events for select to authenticated using(public.app_role()='Administrador');

-- Rutina de extracción: RLS se aplica al usuario que llama, también al exportar.
create procedure public.read_workspace(inout result jsonb) language plpgsql security invoker set search_path='' as $$
begin
 if public.app_role() is null then raise exception 'Cuenta sin acceso al programa' using errcode='42501'; end if;
 select jsonb_build_object(
  'role',public.app_role(),
  'mentorId',(select id from public.mentors where user_id=auth.uid()),
  'menteeId',(select id from public.mentees where user_id=auth.uid()),
  'state',jsonb_build_object(
    'mentors',coalesce((select jsonb_agg(to_jsonb(r)-'user_id' order by name) from public.mentors r),'[]'::jsonb),
    'mentees',coalesce((select jsonb_agg(to_jsonb(e)-'user_id' order by name) from public.mentees e),'[]'::jsonb),
    'mentorships',coalesce((select jsonb_agg(to_jsonb(m)||jsonb_build_object('paidAt',coalesce(m."paidAt"::text,''),'sessions',
      coalesce((select jsonb_agg(to_jsonb(s)||jsonb_build_object('date',coalesce(s.date::text,''),
        'photo',(select to_jsonb(v)-'session_id'-'kind' from public.evidence v where v.session_id=s.id and kind='photo'),
        'document',(select to_jsonb(v)-'session_id'-'kind' from public.evidence v where v.session_id=s.id and kind='document')) order by s.number)
      from public.sessions s where s."mentorshipId"=m.id),'[]'::jsonb)) order by m."sourceNumber") from public.mentorships m),'[]'::jsonb))) into result;
end $$;
create function public.get_workspace() returns jsonb language plpgsql security invoker set search_path='' as $$
declare result jsonb;
begin call public.read_workspace(result); return result; end $$;
create function public.dashboard_summary() returns jsonb language sql stable security invoker set search_path='' as $$
 select jsonb_build_object('mentorships',count(*),'active',count(*) filter(where status='En proceso'),
 'finished',count(*) filter(where status='Terminada'),'hours',coalesce(sum(hours),0)) from public.mentorships
$$;

-- Cada lote se confirma completo o se revierte completo. No se admiten columnas arbitrarias.
create procedure public.apply_changes(commands jsonb) language plpgsql security definer set search_path='' as $$
declare cmd jsonb; patch jsonb; oldrow jsonb; merged jsonb; entity text; rid uuid; mid uuid;
 allowed text[]; assignments text; is_new boolean; actor_role text; expected integer; n integer; field text; attachment jsonb; object_size bigint; object_type text;
begin
 actor_role:=public.app_role();
 if actor_role is null then raise exception 'No autorizado' using errcode='42501'; end if;
 if jsonb_typeof(commands)<>'array' or jsonb_array_length(commands)>100 or octet_length(commands::text)>131072 then raise exception 'Lote inválido'; end if;
 insert into public.write_limits values(auth.uid(),clock_timestamp(),1) on conflict(actor) do update
 set since=case when public.write_limits.since<clock_timestamp()-interval '1 minute' then clock_timestamp() else public.write_limits.since end,
 count=case when public.write_limits.since<clock_timestamp()-interval '1 minute' then 1 else public.write_limits.count+1 end returning count into n;
 if n>120 then raise exception 'Demasiadas solicitudes; espera un minuto' using errcode='P0001'; end if;
 for cmd in select value from jsonb_array_elements(commands) loop
  entity:=cmd->>'entity'; rid:=(cmd->>'id')::uuid; patch:=cmd->'patch'; expected:=(cmd->>'version')::integer;
  if entity not in ('mentors','mentees','mentorships','sessions') or rid is null or jsonb_typeof(patch)<>'object' then raise exception 'Operación inválida'; end if;
  execute format('select to_jsonb(t) from public.%I t where id=$1 for update',entity) into oldrow using rid;
  is_new:=oldrow is null;
  if is_new and actor_role<>'Administrador' then raise exception 'Solo administración puede crear registros' using errcode='42501'; end if;
  if not is_new and (expected is null or expected<>(oldrow->>'version')::integer) then raise exception 'CONFLICT: otro usuario modificó el registro. Recarga antes de guardar.' using errcode='40001'; end if;
  if entity='mentors' then
   allowed:=array['name','title','email','phone','expertise','bio','photo'];
   if actor_role<>'Administrador' and (actor_role<>'Mentor' or oldrow->>'user_id' is distinct from auth.uid()::text) then raise exception 'Perfil ajeno' using errcode='42501'; end if;
  elsif entity='mentees' then
   allowed:=array['name','venture','stage','email','phone','need','photo'];
   if actor_role<>'Administrador' and (actor_role<>'Mentoreado' or oldrow->>'user_id' is distinct from auth.uid()::text) then raise exception 'Perfil ajeno' using errcode='42501'; end if;
  elsif entity='mentorships' then
   allowed:=array['mentorId','menteeId','month','hours','space','status','service','formalization','planningSir','executionSir','paidAt','goal'];
   if not is_new and not public.can_edit_mentorship(rid) then raise exception 'Mentoría ajena' using errcode='42501'; end if;
   if actor_role<>'Administrador' and patch ?| array['mentorId','menteeId','paidAt','formalization','planningSir','executionSir'] then raise exception 'Campo reservado a administración' using errcode='42501'; end if;
   if patch->>'paidAt'='' then patch:=patch||'{"paidAt":null}'::jsonb; end if;
  else
   allowed:=array['date','status','summary','photo','document']; mid:=(oldrow->>'mentorshipId')::uuid;
   if is_new or not public.can_edit_mentorship(mid) then raise exception 'Sesión ajena' using errcode='42501'; end if;
   perform 1 from public.mentorships where id=mid and status='En proceso' for update;
   if not found then raise exception 'Solo se editan sesiones de mentorías en proceso'; end if;
   if patch->>'date'='' then patch:=patch||'{"date":null}'::jsonb; end if;
  end if;
  if exists(select 1 from jsonb_object_keys(patch) k where not k=any(allowed)) then raise exception 'Campo no permitido'; end if;
  if entity in ('mentors','mentees') and patch ? 'photo' and patch->>'photo' is not null then
   if split_part(patch->>'photo','/',1)<>entity or split_part(patch->>'photo','/',2)<>rid::text then raise exception 'Ruta de foto inválida'; end if;
   if not exists(select 1 from storage.objects where bucket_id='mentorias-private' and name=patch->>'photo' and (metadata->>'size')::bigint between 1 and 2097152 and metadata->>'mimetype' in ('image/jpeg','image/png')) then raise exception 'Foto no disponible'; end if;
  end if;
  if entity='sessions' then
   foreach field in array array['photo','document'] loop
    if patch ? field then
     attachment:=patch->field;
     if jsonb_typeof(attachment)<>'object' or (attachment->>'path') is null or split_part(attachment->>'path','/',1)<>'sessions' or split_part(attachment->>'path','/',2)<>mid::text or split_part(attachment->>'path','/',3)<>oldrow->>'number' then raise exception 'Evidencia inválida'; end if;
     select (metadata->>'size')::bigint,metadata->>'mimetype' into object_size,object_type from storage.objects where bucket_id='mentorias-private' and name=attachment->>'path';
     if object_size is null or object_size<>(attachment->>'size')::bigint or object_type is distinct from attachment->>'type' then raise exception 'Archivo no disponible o metadatos incorrectos'; end if;
     insert into public.evidence(session_id,kind,path,name,type,size) values(rid,field,attachment->>'path',attachment->>'name',object_type,object_size)
     on conflict(session_id,kind) do update set path=excluded.path,name=excluded.name,type=excluded.type,size=excluded.size;
    end if;
   end loop;
   patch:=patch-'photo'-'document';
  end if;
  if is_new then
   select string_agg(format('%I',key),','),string_agg(format('(jsonb_populate_record(null::public.%I,$1)).%I',entity,key),',') into assignments,field from jsonb_object_keys(patch||jsonb_build_object('id',rid)) key;
   execute format('insert into public.%I (%s) select %s',entity,assignments,field) using patch||jsonb_build_object('id',rid);
   if entity='mentorships' then insert into public.sessions("mentorshipId",number) select rid,generate_series(1,6); end if;
  else
   merged:=oldrow||patch||jsonb_build_object('version',expected+1);
   select string_agg(format('%I=(jsonb_populate_record(null::public.%I,$1)).%I',key,entity,key),',') into assignments from jsonb_object_keys(patch||jsonb_build_object('version',expected+1)) key;
   execute format('update public.%I set %s where id=$2',entity,assignments) using merged,rid;
  end if;
  insert into public.audit_events(actor,entity,record_id,operation) values(auth.uid(),entity,rid,case when is_new then 'create' else 'update' end);
 end loop;
end $$;

create function public.save_changes(commands jsonb) returns void language plpgsql security definer set search_path='' as $$
begin call public.apply_changes(commands); end $$;

-- Archivos privados. Se autoriza cada ruta; no se permiten sobrescrituras.
create function public.can_access_file(path text, writing boolean) returns boolean language plpgsql stable security definer set search_path='' as $$
declare entity text:=split_part(path,'/',1); rid uuid; owner_id uuid;
begin
 if public.app_role() is null then return false; end if;
 begin rid:=split_part(path,'/',2)::uuid; exception when invalid_text_representation then return false; end;
 if entity='sessions' then
  if writing then return public.can_edit_mentorship(rid) and exists(select 1 from public.mentorships where id=rid and status='En proceso'); end if;
  return public.can_view_mentorship(rid);
 end if;
 if entity='mentors' then select user_id into owner_id from public.mentors where id=rid;
 elsif entity='mentees' then select user_id into owner_id from public.mentees where id=rid;
 else return false; end if;
 if not found then return false; end if;
 if public.app_role()='Administrador' or owner_id=auth.uid() then return true; end if;
 return not writing and exists(select 1 from public.mentorships m where (m."mentorId"=rid or m."menteeId"=rid) and public.can_view_mentorship(m.id));
end $$;
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
 values('mentorias-private','mentorias-private',false,5242880,array['image/png','image/jpeg','application/pdf']);
create policy mentorias_files_read on storage.objects for select to authenticated using(bucket_id='mentorias-private' and public.can_access_file(name,false));
create policy mentorias_files_insert on storage.objects for insert to authenticated with check(bucket_id='mentorias-private' and public.can_access_file(name,true));

revoke all on public.app_profiles,public.mentors,public.mentees,public.mentorships,public.sessions,public.evidence,public.audit_events,public.write_limits from anon,authenticated;
grant select on public.app_profiles,public.mentors,public.mentees,public.mentorships,public.sessions,public.evidence,public.audit_events to authenticated;
revoke all on function public.app_role(),public.can_view_mentorship(uuid),public.can_edit_mentorship(uuid),public.get_workspace(),public.dashboard_summary(),public.save_changes(jsonb),public.can_access_file(text,boolean) from public,anon;
grant execute on function public.app_role(),public.can_view_mentorship(uuid),public.can_edit_mentorship(uuid),public.get_workspace(),public.dashboard_summary(),public.save_changes(jsonb),public.can_access_file(text,boolean) to authenticated;
revoke all on procedure public.apply_changes(jsonb),public.read_workspace(jsonb) from public,anon,authenticated;
grant execute on procedure public.read_workspace(jsonb) to authenticated;
commit;
